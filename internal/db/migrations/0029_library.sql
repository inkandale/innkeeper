-- Every card and lorebook belongs to one library. Rows written without a
-- library go to library 1.
CREATE TABLE library (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name text NOT NULL UNIQUE CHECK (name <> ''),
    created_at timestamptz NOT NULL DEFAULT now()
);

INSERT INTO library (id, name) VALUES (1, 'Library');
SELECT setval(pg_get_serial_sequence('library', 'id'), 1);

ALTER TABLE card ADD COLUMN library_id bigint NOT NULL DEFAULT 1 REFERENCES library DEFERRABLE INITIALLY IMMEDIATE;
ALTER TABLE lorebook ADD COLUMN library_id bigint NOT NULL DEFAULT 1 REFERENCES library DEFERRABLE INITIALLY IMMEDIATE;
CREATE INDEX ON card (library_id);
CREATE INDEX ON lorebook (library_id);
